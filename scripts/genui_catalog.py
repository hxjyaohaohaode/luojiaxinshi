"""Generate browser/schema/prompt artifacts from the one hand-maintained catalog."""
from pathlib import Path
import argparse
import hashlib
import json

ROOT=Path(__file__).resolve().parent.parent
def outputs():
    catalog=json.loads((ROOT/'schema/genui/catalog.json').read_text(encoding='utf-8'))
    canonical=json.dumps(catalog,ensure_ascii=False,separators=(',',':'))
    digest=hashlib.sha256(canonical.encode()).hexdigest()
    module='// Generated by scripts/genui_catalog.py; edit schema/genui/catalog.json only.\nexport const CATALOG='+canonical+';\nexport const CATALOG_HASH="'+digest+'";\n'
    def signature(schema):
        if 'enum' in schema:return '|'.join(str(v) for v in schema['enum'])
        kind=schema.get('type','any')
        if isinstance(kind,list):return '值'
        if kind=='array':return '['+signature(schema.get('items',{}))+']'
        if kind=='object' and 'properties' in schema:return '{'+','.join(k+('' if k in schema.get('required',[]) else '?')+':'+signature(v) for k,v in schema['properties'].items())+'}'
        return {'string':'s','number':'n','integer':'i','boolean':'b','object':'obj'}.get(kind,kind)
    groups={}
    for name,c in catalog['components'].items():
        shape='('+','.join(k+('' if k in c['required'] else '?')+':'+signature(v) for k,v in c['properties'].items() if k not in {'status','error','fallback','visible'})+')'+(' children:ids' if c['children'] else '')
        groups.setdefault(shape,[]).append(name)
    capabilities='genui v1；s=字符串,n=数值,i=整数,b=布尔,?=可省略。所有节点均可用 visible:b（含绑定/表达式）条件显示。\n'+'\n'.join('/'.join(names)+shape for shape,names in groups.items())+'\n'
    capabilities+='纯函数：'+','.join(catalog['functions'])+'。\n'
    schema={'$schema':'https://json-schema.org/draft/2020-12/schema','$id':'urn:campus:genui:v1','title':'genui v1 操作','oneOf':[],'$defs':{}}
    binding={'oneOf':[{'type':'object','properties':{key:{'type':'string','maxLength':catalog['limits']['expressionChars'] if key=='$expr' else 200}},'required':[key],'additionalProperties':False} for key in ('$bind','$expr','$ref')]}
    schema['$defs']['Binding']=binding
    def dynamic(prop):
        literal=dict(prop)
        if 'properties' in literal:literal['properties']={key:dynamic(value) for key,value in literal['properties'].items()}
        if 'items' in literal:literal['items']=dynamic(literal['items'])
        return {'anyOf':[literal,{'$ref':'#/$defs/Binding'}]}
    for name,c in catalog['components'].items():
        schema['$defs'][name]={'type':'object','properties':{key:dynamic(value) for key,value in c['properties'].items()},'required':c['required'],'additionalProperties':False}
    for op,required,props in [('begin',['v'],{'v':{'const':1}}),('state',['set'],{'set':{'type':'object'}}),('data',['id','value'],{'id':{'type':'string'},'value':{}}),('node',['id','type'],{'id':{'type':'string'},'type':{'type':'string'},'props':{'type':'object'},'children':{'type':'array','items':{'type':'string'}},'on':{'type':'object'}}),('patch',['id'],{'id':{'type':'string'},'props':{'type':'object'},'children':{'type':'array','items':{'type':'string'}},'on':{'type':'object'}}),('end',[],{})]:
        entry={'type':'object','properties':{'op':{'const':op},**props},'required':['op',*required],'additionalProperties':False}
        if op=='node':
            entry['allOf']=[{'if':{'properties':{'type':{'const':name}},'required':['type']},'then':{'properties':{'props':{'$ref':'#/$defs/'+name}}}} for name in catalog['components']]
        schema['oneOf'].append(entry)
    gallery=json.loads((ROOT/'fixtures/genui/gallery.json').read_text(encoding='utf-8')) if (ROOT/'fixtures/genui/gallery.json').exists() else {}
    scenarios=json.loads((ROOT/'fixtures/genui/scenarios.json').read_text(encoding='utf-8'))
    return {'static/genui/scenarios.js':'// Generated engineering composition fixtures.\nexport const SCENARIOS='+json.dumps(scenarios,ensure_ascii=False,separators=(',',':'))+';\n','static/genui/catalog.js':module,'docs/genui/CAPABILITIES.txt':capabilities,'schema/genui/protocol.schema.json':json.dumps(schema,ensure_ascii=False,indent=2)+'\n','static/genui/fixtures.js':'// Generated from fixtures/genui/gallery.json. Engineering examples only.\nexport const SAMPLES='+json.dumps(gallery,ensure_ascii=False,separators=(',',':'))+';\n'}

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,content in outputs().items():
        path=ROOT/name
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8')!=content: raise SystemExit('Generated artifact drift: '+name)
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content,encoding='utf-8',newline='\r\n')
    print('genui catalog artifacts match' if args.check else 'genui catalog artifacts generated')
