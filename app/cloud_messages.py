"""Aliyun SDKs and QQ SMTP/TLS. Never logs secrets, OTPs or response bodies."""
import json
from fastapi import HTTPException


class CloudMessages:
    def __init__(self, settings):
        self.settings = settings

    def available(self, channel):
        s = self.settings
        if channel=='email' and s.mail_provider=='qq_smtp':
            return bool(s.smtp_username and s.smtp_authorization_code)
        credentials = bool(s.aliyun_access_key_id and s.aliyun_access_key_secret)
        return credentials and bool(s.sms_sign_name if channel == 'sms' else s.mail_sender)

    def send_code(self, channel, destination, code, purpose, request_id):
        if not self.available(channel):
            raise HTTPException(503, '短信通道尚未配置' if channel == 'sms' else '邮箱通道尚未配置')
        if channel == 'email':
            description={'register':'注册账号','login':'登录账号','recover':'找回密码',
                         'password':'修改密码','contact_bind':'绑定新联系方式','contact_authorize':'验证原联系方式'}[purpose]
            return self.send_mail(destination, '珞珈信使 · 身份验证码',
                f'你的验证码是 {code}，5 分钟内有效。用途：{description}。\n'
                '请勿向任何人提供验证码。如果不是你本人操作，请忽略此邮件。')
        from alibabacloud_dypnsapi20170525.client import Client
        from alibabacloud_dypnsapi20170525.models import SendSmsVerifyCodeRequest
        from alibabacloud_tea_openapi.models import Config
        from alibabacloud_tea_util.models import RuntimeOptions
        s = self.settings
        client = Client(Config(access_key_id=s.aliyun_access_key_id, access_key_secret=s.aliyun_access_key_secret,
                               endpoint='dypnsapi.aliyuncs.com', protocol='https'))
        # Explicit custom code: validation is performed by verification.py, NOT by
        # CheckSmsVerifyCode (which only validates codes generated by Aliyun).
        template = {'register':'100001','login':'100001','recover':'100003',
                    'password':'100003','contact_bind':'100004','contact_authorize':'100005'}[purpose]
        request = SendSmsVerifyCodeRequest(phone_number=destination, country_code='86',
            sign_name=s.sms_sign_name, template_code=template, scheme_name=s.sms_scheme_name,
            template_param=json.dumps({'code':code,'min':'5'}), out_id=request_id,
            return_verify_code=False, valid_time=300, interval=60, code_length=6,
            duplicate_policy=1, auto_retry=0)
        try:
            body = client.send_sms_verify_code_with_options(request,
                RuntimeOptions(autoretry=False, connect_timeout=5000, read_timeout=10000)).body
            if body.code != 'OK' or body.success is not True:
                raise ValueError('provider_rejected')
            return body.request_id or request_id
        except Exception:
            raise HTTPException(502, '短信提交未确认成功，请稍后重试；请勿连续点击发送') from None

    def send_mail(self, destination, subject, body):
        if not self.available('email'):
            raise HTTPException(503, '邮箱通道尚未配置')
        if self.settings.mail_provider=='qq_smtp':
            return self._qq_mail(destination,subject,body)
        from alibabacloud_dm20151123.client import Client
        from alibabacloud_dm20151123.models import SingleSendMailRequest
        from alibabacloud_tea_openapi.utils_models import Config
        from darabonba.runtime import RuntimeOptions
        s = self.settings
        endpoints = {'cn-hangzhou':'dm.aliyuncs.com','ap-southeast-1':'dm.ap-southeast-1.aliyuncs.com',
                     'ap-southeast-2':'dm.ap-southeast-2.aliyuncs.com','us-east-1':'dm.us-east-1.aliyuncs.com',
                     'eu-central-1':'dm.eu-central-1.aliyuncs.com'}
        client = Client(Config(access_key_id=s.aliyun_access_key_id, access_key_secret=s.aliyun_access_key_secret,
                               region_id=s.mail_region, endpoint=endpoints[s.mail_region], protocol='https'))
        request = SingleSendMailRequest(account_name=s.mail_sender, address_type=1, reply_to_address=False,
            to_address=destination, subject=subject, text_body=body, from_alias='珞珈信使')
        try:
            response = client.single_send_mail_with_options(request,
                RuntimeOptions(autoretry=False, connect_timeout=5000, read_timeout=10000))
            if not response.body or not response.body.request_id:raise ValueError('missing_receipt')
            return response.body.request_id
        except Exception:
            raise HTTPException(502, '邮件提交未确认成功，请稍后重试并检查垃圾邮件') from None

    def _qq_mail(self,destination,subject,body):
        import smtplib
        import ssl
        from email.message import EmailMessage
        from email.headerregistry import Address
        from email.utils import make_msgid
        s=self.settings
        try:
            message=EmailMessage()
            message['From']=Address('珞珈信使',addr_spec=s.smtp_username)
            message['To']=Address(addr_spec=destination)
            message['Subject']=subject
            message['Message-ID']=make_msgid(domain='qq.com')
            message.set_content(body)
            # No clear-text SMTP, debug logging, provider fallback or retries.
            with smtplib.SMTP_SSL('smtp.qq.com',465,timeout=10,context=ssl.create_default_context()) as client:
                client.login(s.smtp_username,s.smtp_authorization_code)
                refused=client.send_message(message,from_addr=s.smtp_username,to_addrs=[destination])
                if refused:raise ValueError('recipient_refused')
            return str(message['Message-ID'])
        except Exception:
            raise HTTPException(502,'邮件提交未确认成功，请稍后重试并检查垃圾邮件') from None
